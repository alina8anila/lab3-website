def create_data(apps, schema_editor):
    Department = apps.get_model("fgn", "Department")
    Program = apps.get_model("fgn", "Program")
    Teacher = apps.get_model("fgn", "Teacher")
    HomePageContent = apps.get_model("fgn", "HomePageContent")

    Program.objects.all().delete()
    Teacher.objects.all().delete()
    HomePageContent.objects.all().delete()
    Department.objects.all().delete()

    departments = {}
    heads = {}
    for key, name, head in DEPARTMENTS:
        departments[key] = Department.objects.create(name=name, head=head)
        heads[key] = head

    for level, name, code, key, description in PROGRAMS:
        Program.objects.create(
            name=name,
            level=level,
            code=code,
            description=description,
            coordinator_name=heads[key],
            coordinator_email=FGN_EMAIL,
            department=departments[key],
        )

    for key, name, position, degree in TEACHERS:
        Teacher.objects.create(
            name=name,
            position=position,
            degree=degree,
            department=departments[key],
        )

    HomePageContent.objects.create(**HOME)


